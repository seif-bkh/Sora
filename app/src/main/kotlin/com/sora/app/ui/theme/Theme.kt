/**
 * Sora's Material 3 theme.
 *
 * @param darkTheme defaults to dark regardless of the system setting. The
 *   project brief specifies dark as the app default given the content domain;
 *   Phase 8 exposes a settings toggle (system / light / dark) that will drive
 *   this parameter, at which point the system setting becomes one option
 *   rather than the fallback.
 * @param dynamicColor Material You wallpaper-derived colour, Android 12+ only.
 *   Falls back to the static brand palette seeded from #4A90E2 elsewhere.
 */
@Composable
fun SoraTheme(
    darkTheme: Boolean = true,
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> SoraDarkColors
        else -> SoraLightColors
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = SoraTypography,
        content = content,
    )
}
